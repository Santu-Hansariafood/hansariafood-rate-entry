import { NextResponse, after } from "next/server";
import { connectDB } from "@/lib/mongodb";
import SaudaEntry from "@/models/SaudaEntry";
import { generateSaudaExcel } from "@/lib/excel/generateSaudaExcel";
import { sendSaudaEmail } from "@/lib/email/sendSaudaEmail";
import {
  buildSaudaEntryGroups,
  generateSaudaEmailTemplate,
} from "@/lib/email/templates/saudaTemplate";
import { verifyApiKey } from "@/middleware/apiKeyMiddleware/apiKeyMiddleware";
import { rateLimitGuard } from "@/lib/apiUtils";

const REPORT_TIME_ZONE = "Asia/Kolkata";

const formatSaudaDate = (date) => {
  const { day, month, year } = Object.fromEntries(
    new Intl.DateTimeFormat("en-GB", {
      timeZone: REPORT_TIME_ZONE,
      day: "2-digit",
      month: "2-digit",
      year: "numeric",
    })
      .formatToParts(date)
      .map(({ type, value }) => [type, value]),
  );
  return `${day}-${month}-${year}`;
};

const formatReadableDate = (date) =>
  new Intl.DateTimeFormat("en-GB", {
    timeZone: REPORT_TIME_ZONE,
    day: "2-digit",
    month: "long",
    year: "numeric",
  }).format(date);

const formatReportTime = (date) =>
  new Intl.DateTimeFormat("en-IN", {
    timeZone: REPORT_TIME_ZONE,
    hour: "numeric",
    minute: "2-digit",
    hour12: true,
  }).format(date);

export async function POST(req) {
  const limited = rateLimitGuard(req, "write");
  if (limited) return limited;

  await connectDB();
  if (!verifyApiKey(req)) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  try {
    const { to } = await req.json();
    if (!to) {
      return NextResponse.json(
        { error: "Missing 'to' email address" },
        { status: 400 },
      );
    }

    const now = new Date();
    const todayStr = formatSaudaDate(now);

    // Only today's sauda entries are shared; previous days are excluded.
    const saudaEntries = await SaudaEntry.find({ date: todayStr })
      .sort({ createdAt: 1 })
      .lean();

    if (saudaEntries.length === 0) {
      return NextResponse.json(
        { error: "No sauda entries found for today" },
        { status: 404 },
      );
    }

    const buffer = await generateSaudaExcel(saudaEntries);

    const html = generateSaudaEmailTemplate({
      company: "Hansaria Food",
      date: formatReadableDate(now),
      time: formatReportTime(now),
      saudaEntries: await buildSaudaEntryGroups(saudaEntries),
      showCompany: true,
      infoText: "Automated daily Sauda report generated by Hansaria Food.",
    });

    const filename = `sauda-${todayStr}.xlsx`;
    const subject = `Daily Sauda Report - ${formatReadableDate(now)}`;

    // Delivery happens after the response is flushed so the export stays snappy.
    after(async () => {
      try {
        await sendSaudaEmail({ to, buffer, filename, html, subject });
      } catch (emailError) {
        console.error("Failed to send sauda report email:", emailError);
      }
    });

    return NextResponse.json(
      { message: "Email queued for delivery" },
      { status: 200 },
    );
  } catch (error) {
    console.error("Error in POST /send-sauda-email:", error);
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}
