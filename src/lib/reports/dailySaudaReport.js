import { connectDB } from "../mongodb.js";
import SaudaEntry from "../../models/SaudaEntry.js";
import { sendEmail } from "../email/sendEmail.js";
import { generateSaudaExcel } from "../excel/generateSaudaExcel.js";
import {
  buildSaudaEntryGroups,
  generateSaudaEmailTemplate,
} from "../email/templates/saudaTemplate.js";

const REPORT_TIME_ZONE = "Asia/Kolkata";
const RECIPIENTS = ["gopal@hansariafood.com", "sauda@hansariafood.com"];
let isSendingDailySaudaReport = false;

const formatReportDate = (date) =>
  new Intl.DateTimeFormat("en-GB", {
    timeZone: REPORT_TIME_ZONE,
    day: "2-digit",
    month: "short",
    year: "numeric",
  }).format(date);

const formatReportTime = (date) =>
  new Intl.DateTimeFormat("en-IN", {
    timeZone: REPORT_TIME_ZONE,
    hour: "numeric",
    minute: "2-digit",
    hour12: true,
  }).format(date);

const formatFileDate = (date) => {
  const dateParts = new Intl.DateTimeFormat("en-GB", {
    timeZone: REPORT_TIME_ZONE,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(date);
  const parts = Object.fromEntries(
    dateParts.map(({ type, value }) => [type, value])
  );
  return `${parts.year}-${parts.month}-${parts.day}`;
};

// SaudaEntry.date is stored as DD-MM-YYYY (IST), so the daily report filters
// on that exact string to exclude all previous days' data.
const formatSaudaDate = (date) => {
  const dateParts = new Intl.DateTimeFormat("en-GB", {
    timeZone: REPORT_TIME_ZONE,
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
  }).formatToParts(date);
  const parts = Object.fromEntries(
    dateParts.map(({ type, value }) => [type, value])
  );
  return `${parts.day}-${parts.month}-${parts.year}`;
};

const countSaudas = (entries) =>
  entries.reduce((total, entry) => {
    const groups =
      entry.saudaEntries instanceof Map
        ? [...entry.saudaEntries.values()]
        : Object.values(entry.saudaEntries || {});
    return (
      total +
      groups.reduce(
        (groupTotal, list) =>
          groupTotal + (Array.isArray(list) ? list.length : 0),
        0
      )
    );
  }, 0);

export async function sendDailySaudaReport() {
  if (isSendingDailySaudaReport) {
    console.log("[daily-sauda-report] A report is already being generated.");
    return { sent: false, reason: "already-running" };
  }

  isSendingDailySaudaReport = true;

  try {
    await connectDB();

    const now = new Date();
    const todayStr = formatSaudaDate(now);

    const entries = await SaudaEntry.find({ date: todayStr })
      .sort({ createdAt: 1 })
      .lean();

    if (countSaudas(entries) === 0) {
      console.log(
        "[daily-sauda-report] No Sauda entries for today, nothing to send.",
      );
      return { sent: false, reason: "no-entries" };
    }

    const buffer = await generateSaudaExcel(entries);
    const filename = `sauda-${formatFileDate(now)}.xlsx`;
    const reportDate = formatReportDate(now);

    const html = generateSaudaEmailTemplate({
      company: "Hansaria Food",
      date: reportDate,
      time: formatReportTime(now),
      saudaEntries: buildSaudaEntryGroups(entries),
      showCompany: true,
      infoText: "Automated daily Sauda report generated by Hansaria Food.",
    });

    await sendEmail({
      to: RECIPIENTS.join(", "),
      subject: `Daily Sauda Report - ${reportDate}`,
      text: `Please find attached today's Sauda report (${todayStr}) containing only the entries saved today.`,
      html,
      attachments: [
        {
          filename,
          content: buffer,
          contentType:
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        },
      ],
    });

    console.log(
      `[daily-sauda-report] Sent "${filename}" with today's entries to ${RECIPIENTS.join(", ")}.`,
    );
    return { sent: true, filename, recipients: RECIPIENTS.length };
  } finally {
    isSendingDailySaudaReport = false;
  }
}
